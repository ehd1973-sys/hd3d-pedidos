import {PGlite} from '@electric-sql/pglite';
import fs from 'node:fs';
import assert from 'node:assert/strict';
import vm from 'node:vm';
const db=new PGlite();
await db.exec("create schema auth; create role authenticated; create role anon; create table auth.users(id uuid primary key); create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;");
const base=fs.readFileSync('homologacao-base.sql','utf8').replace(/^\uFEFF/,'');
await db.exec(base);
assert.equal((await db.query('select count(*)::int n from pedidos')).rows[0].n,1);
assert.equal((await db.query("select count(*)::int n from pg_class where relnamespace='public'::regnamespace and relkind='r' and relrowsecurity")).rows[0].n,5);
await assert.rejects(db.exec(base));await db.exec('rollback');
await db.exec(fs.readFileSync('fase1.sql','utf8'));
assert.equal((await db.query("select count(*)::int n from pg_class where relnamespace='public'::regnamespace and relkind='r' and relrowsecurity")).rows[0].n,10);
const html=fs.readFileSync('homologacao.html','utf8');
const script=html.match(/<script>\s*([\s\S]*?)<\/script>/)[1];
new vm.Script(script);
assert.match(script,/const CONFIG = \{url: '', chave: ''\}/);
assert.match(script,/hd3d_homologacao_cfg/);
assert.match(script,/Projeto de produção recusado/);
console.log('Homologação: base vazia instalada, RLS em dez tabelas, reinstalação recusada e página sem configuração de produção: OK.');
await db.close();
