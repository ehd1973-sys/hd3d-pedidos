CREATE OR REPLACE FUNCTION public.mudar_status(p_id uuid, p_status text, p_hist jsonb)
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if not public.tem('ativo') then raise exception 'sem permissão'; end if;
  if p_status not in ('Orçamento','Aprovado','Imprimindo','Pronto','Entregue','Cancelado') then
    raise exception 'status inválido';
  end if;
  update public.pedidos
     set dados = jsonb_set(jsonb_set(dados, '{status}', to_jsonb(p_status)),
                           '{historico}', coalesce(dados->'historico','[]'::jsonb) || jsonb_build_array(p_hist)),
         atualizado_em = now()
   where id = p_id;
end $function$;
CREATE OR REPLACE FUNCTION public.ajustar_numeracao()
 RETURNS void
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  if not public.tem('master') then raise exception 'apenas o master'; end if;
  perform setval(pg_get_serial_sequence('public.pedidos','numero'),
                 coalesce((select max(numero) from public.pedidos), 0) + 1, false);
end $function$;
CREATE OR REPLACE FUNCTION public.tem(perm text)
 RETURNS boolean
 LANGUAGE sql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
  select coalesce((
    select ativo and (master or case perm
      when 'ativo'      then true
      when 'editar'     then editar
      when 'excluir'    then excluir
      when 'despesas'   then despesas
      when 'financeiro' then ver_financeiro
      when 'producao'   then producao
      else false end)
    from public.perfis where id = auth.uid()), false);
$function$;
CREATE OR REPLACE FUNCTION public._hist(d jsonb, texto text, por text)
 RETURNS jsonb
 LANGUAGE sql
 IMMUTABLE
AS $function$
  select jsonb_set(d, '{historico}', coalesce(d->'historico','[]'::jsonb) ||
    jsonb_build_array(jsonb_build_object(
      'data', to_char(now() at time zone 'America/Sao_Paulo','DD/MM/YYYY, HH24:MI:SS'),
      'texto', texto, 'por', por)));
$function$;
CREATE OR REPLACE FUNCTION public.lancar_producao(p_pedido uuid, p_pecas integer, p_logos integer)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare d jsonb; q integer; sep boolean; fp integer; fl integer; st text; novo text; por text;
        pc integer := coalesce(p_pecas,0); lg integer := coalesce(p_logos,0); txt text;
begin
  if not public.tem('producao') then raise exception 'sem permissão para lançar produção'; end if;
  if pc < 0 or lg < 0 or pc + lg = 0 then raise exception 'informe a quantidade produzida'; end if;
  select dados into d from public.pedidos where id = p_pedido for update;
  if d is null then raise exception 'pedido não encontrado'; end if;
  q   := floor(coalesce(nullif(d->>'qtde','')::numeric,0));
  sep := coalesce((d->>'logoSeparada')::boolean,false);
  if not sep and lg > 0 then raise exception 'este pedido não tem logo impressa separada'; end if;
  select coalesce(sum(pecas),0), coalesce(sum(logos),0) into fp, fl from public.producao where pedido_id = p_pedido;
  if fp + pc > q then raise exception 'peças acima do total do pedido (faltam %)', q - fp; end if;
  if fl + lg > q then raise exception 'logos acima do total do pedido (faltam %)', q - fl; end if;
  por := coalesce((select email from public.perfis where id = auth.uid()),'');
  insert into public.producao(pedido_id,pecas,logos,por) values (p_pedido,pc,lg,por);
  fp := fp + pc; fl := fl + lg;
  st := coalesce(d->>'status','Orçamento'); novo := st;
  if fp >= q and (not sep or fl >= q) then
    if st not in ('Entregue','Cancelado') then novo := 'Pronto'; end if;
  elsif st in ('Orçamento','Aprovado','Pronto') then
    novo := 'Imprimindo';
  end if;
  txt := 'Produção: +' || pc || ' peça(s)' || case when sep then ', +' || lg || ' logo(s)' else '' end ||
         ' — peças ' || fp || '/' || q || case when sep then ', logos ' || fl || '/' || q else '' end ||
         case when novo <> st then ' · status: ' || st || ' → ' || novo else '' end;
  d := jsonb_set(public._hist(d, txt, por), '{status}', to_jsonb(novo));
  update public.pedidos set dados = d, atualizado_em = now() where id = p_pedido;
  return jsonb_build_object('pecas',fp,'logos',fl,'status',novo);
end $function$;
CREATE OR REPLACE FUNCTION public.desfazer_producao(p_id uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare r public.producao; d jsonb; q integer; sep boolean; fp integer; fl integer; st text; novo text; por text;
begin
  if not public.tem('producao') then raise exception 'sem permissão para lançar produção'; end if;
  select * into r from public.producao where id = p_id;
  if r.id is null then raise exception 'lançamento não encontrado'; end if;
  select dados into d from public.pedidos where id = r.pedido_id for update;
  delete from public.producao where id = p_id;
  q   := floor(coalesce(nullif(d->>'qtde','')::numeric,0));
  sep := coalesce((d->>'logoSeparada')::boolean,false);
  select coalesce(sum(pecas),0), coalesce(sum(logos),0) into fp, fl from public.producao where pedido_id = r.pedido_id;
  st := coalesce(d->>'status','Orçamento'); novo := st;
  if st = 'Pronto' and not (fp >= q and (not sep or fl >= q)) then novo := 'Imprimindo'; end if;
  por := coalesce((select email from public.perfis where id = auth.uid()),'');
  d := jsonb_set(public._hist(d,
        'Produção desfeita: -' || r.pecas || ' peça(s)' || case when sep then ', -' || r.logos || ' logo(s)' else '' end ||
        ' — peças ' || fp || '/' || q || case when sep then ', logos ' || fl || '/' || q else '' end ||
        case when novo <> st then ' · status: ' || st || ' → ' || novo else '' end, por),
       '{status}', to_jsonb(novo));
  update public.pedidos set dados = d, atualizado_em = now() where id = r.pedido_id;
  return jsonb_build_object('pecas',fp,'logos',fl,'status',novo);
end $function$;
